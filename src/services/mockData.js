// ─── Book Code Generator ──────────────────────────
function generateBookCode(year, genre, innerGenre, copyNum) {
  const y = String(year).slice(-2);
  const g = genre.slice(0, 3).toUpperCase();
  const ig = innerGenre.slice(0, 2).toUpperCase();
  const c = String(copyNum).padStart(3, '0');
  return `${y}${g}${ig}${c}`;
}

